#!/usr/bin/env node
// Builds bundle/: the server and its dependencies in a few files, which the Claude Code plugin runs with `node`.
// Run with npx, a GitHub install keeps an `npm exec` process alive next to the server: twice the memory and about
// 2.5 s to start (measured 2026-11-17: 103 MB and 2.5 s through npx, 48 MB and 0.1 s from the bundle).
// The bundle is committed with the source it is built from; test/bundle.test.ts fails when it is out of date.
//   node scripts/bundle.mjs [outdir]   (default bundle/)
import { build } from "esbuild";
import { createHash } from "node:crypto";
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const out = process.argv[2] ?? "bundle";
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
await build({
  entryPoints: { index: "src/index.ts" },
  bundle: true,
  splitting: true,
  format: "esm",
  platform: "node",
  target: "node20",
  outdir: out,
  // Optional, loaded only for audit_page with render: true.
  external: ["playwright-core"],
  // Bundled CommonJS dependencies call require() for Node's own modules.
  banner: { js: "// Generated by scripts/bundle.mjs from src/. Do not edit.\nimport { createRequire as __createRequire } from 'node:module';\nconst require = __createRequire(import.meta.url);" },
  legalComments: "eof",
  logLevel: "warning",
});
// No commit in here: the bundle is committed with its source, so that commit doesn't exist yet. The hash of the files
// identifies the build; the server compares it with main's (src/lib/version.ts).
const files = readdirSync(out).filter((f) => f.endsWith(".js")).sort();
const h = createHash("sha256");
for (const f of files) h.update(f).update("\0").update(readFileSync(join(out, f))).update("\0");
writeFileSync(join(out, "build-info.json"), JSON.stringify({ bundle: h.digest("hex") }, null, 2) + "\n");
writeFileSync(join(out, "package.json"), JSON.stringify({ type: "module" }, null, 2) + "\n");
console.error(`bundle: ${files.length} files in ${out}/`);
